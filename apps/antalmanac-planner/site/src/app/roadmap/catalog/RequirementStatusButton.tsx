const getWedgePath = (pct: number) => {
    const angle = (pct / 100) * 2 * Math.PI - Math.PI / 2;
    const endX = CENTER + WEDGE_RADIUS * Math.cos(angle);
    const endY = CENTER + WEDGE_RADIUS * Math.sin(angle);
    const largeArc = pct > 50 ? 1 : 0;

    return [
        `M ${CENTER} ${CENTER}`,
        `L ${CENTER} ${CENTER - WEDGE_RADIUS}`,
        `A ${WEDGE_RADIUS} ${WEDGE_RADIUS} 0 ${largeArc} 1 ${endX} ${endY}`,
        'Z',
    ].join(' ');
};

interface ProgressIconProps extends SvgIconProps {
    percentage: number;
}

export const ProgressIcon = ({ percentage, ...props }: ProgressIconProps) => {
    const pct = Math.min(100, Math.max(0, percentage));

    return (
        <SvgIcon {...props}>
            <path d={RING_PATH} />

            {/* Progress fill */}
            {pct >= 100 ? (
                <circle cx={CENTER} cy={CENTER} r={WEDGE_RADIUS} />
            ) : (
                pct > 0 && <path d={getWedgePath(pct)} />
            )}
        </SvgIcon>
    );
};
